//! Counters for what napi-rs releases when an env that loaded this addon is
//! torn down. They are process-wide, so a test reads them before and after a
//! worker that loads the addon and exits.

use napi::bindgen_prelude::*;
use napi_derive::napi;

/// How many cached `Reflect` holder references env teardown has deleted in this
/// process. Each load of the addon caches one, so each torn-down load must add
/// exactly one.
#[napi]
pub fn reflect_refs_deleted_at_teardown() -> u32 {
  napi::bindgen_prelude::env_teardown_reflect_refs_deleted() as u32
}

/// How many custom-GC threadsafe functions env teardown has released in this
/// process. Each load of the addon creates one, so each torn-down load must add
/// exactly one.
#[napi]
pub fn custom_gc_tsfns_released_at_teardown() -> u32 {
  napi::bindgen_prelude::env_teardown_custom_gc_released() as u32
}

/// How many class constructor references env teardown has deleted in this
/// process. Each load of the addon defines every `#[napi]` class once, so each
/// torn-down load must add the same amount.
#[napi]
pub fn class_refs_deleted_at_teardown() -> u32 {
  napi::bindgen_prelude::env_teardown_class_refs_deleted() as u32
}

/// The `NinjaTurtle` constructor as code generated by an older napi-derive finds
/// it: through `get_class_constructor`, which takes no env and answers with the
/// newest live load on this thread that defined the class.
#[napi]
pub fn legacy_ninja_turtle_constructor(env: &Env) -> Result<Unknown<'_>> {
  let ctor_ref =
    napi::bindgen_prelude::get_class_constructor("NinjaTurtle\0").ok_or_else(|| {
      Error::new(
        Status::GenericFailure,
        "Failed to get constructor of class `NinjaTurtle`",
      )
    })?;
  let mut ctor = std::ptr::null_mut();
  check_status!(
    unsafe { napi::sys::napi_get_reference_value(env.raw(), ctor_ref, &mut ctor) },
    "Failed to get constructor reference of class `NinjaTurtle`"
  )?;
  Ok(unsafe { Unknown::from_raw_unchecked(env.raw(), ctor) })
}

/// What happened to the references released through the custom-GC handles of this process
/// (Buffers, TypedArrays, Errors and function references dropped off their env's JS thread, or
/// during its teardown).
#[napi(object)]
pub struct CustomGcRefCounts {
  /// Deleted while their env ran.
  pub deleted_while_running: u32,
  /// Deleted at env teardown, by the cleanup hook or the late sentinel.
  pub deleted_at_teardown: u32,
  /// Released too late in env teardown to be deleted: leaked.
  pub leaked_at_teardown: u32,
  /// Still waiting when their env's handle was freed: leaked.
  pub left_pending: u32,
  /// Custom-GC callbacks that deleted references.
  pub drain_callbacks: u32,
  /// The most references one custom-GC callback deleted.
  pub largest_drain: u32,
}

#[napi]
pub fn custom_gc_ref_counts() -> CustomGcRefCounts {
  let counters = napi::bindgen_prelude::custom_gc_ref_counters();
  CustomGcRefCounts {
    deleted_while_running: counters.deleted_while_running as u32,
    deleted_at_teardown: counters.deleted_at_teardown as u32,
    leaked_at_teardown: counters.leaked_at_teardown as u32,
    left_pending: counters.left_pending as u32,
    drain_callbacks: counters.drain_callbacks as u32,
    largest_drain: counters.largest_drain as u32,
  }
}

static BUFFERS_DROPPED_OFF_THREAD: std::sync::atomic::AtomicU32 =
  std::sync::atomic::AtomicU32::new(0);

/// Drops `buffers` on a new thread, then counts them in `buffersDroppedOffThread`.
#[napi]
pub fn drop_buffers_off_thread(buffers: Vec<Buffer>) {
  std::thread::spawn(move || {
    let count = buffers.len() as u32;
    drop(buffers);
    BUFFERS_DROPPED_OFF_THREAD.fetch_add(count, std::sync::atomic::Ordering::SeqCst);
  });
}

/// How many Buffers `dropBuffersOffThread` has dropped in this process.
#[napi]
pub fn buffers_dropped_off_thread() -> u32 {
  BUFFERS_DROPPED_OFF_THREAD.load(std::sync::atomic::Ordering::SeqCst)
}
