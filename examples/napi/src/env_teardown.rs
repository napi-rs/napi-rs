//! Counters for what napi-rs releases when an env that loaded this addon is
//! torn down. They are process-wide, so a test reads them before and after a
//! worker that loads the addon and exits.

use napi::bindgen_prelude::*;
use napi_derive::napi;

/// How many cached `Reflect` holder references env teardown has deleted in this
/// process. Each load of the addon caches one, so each torn-down load must add
/// exactly one.
#[napi]
pub fn reflect_refs_deleted_at_teardown() -> u32 {
  napi::bindgen_prelude::env_teardown_reflect_refs_deleted() as u32
}

/// How many custom-GC threadsafe functions env teardown has released in this
/// process. Each load of the addon creates one, so each torn-down load must add
/// exactly one.
#[napi]
pub fn custom_gc_tsfns_released_at_teardown() -> u32 {
  napi::bindgen_prelude::env_teardown_custom_gc_released() as u32
}

/// How many class constructor references env teardown has deleted in this
/// process. Each load of the addon defines every `#[napi]` class once, so each
/// torn-down load must add the same amount.
#[napi]
pub fn class_refs_deleted_at_teardown() -> u32 {
  napi::bindgen_prelude::env_teardown_class_refs_deleted() as u32
}

/// The `NinjaTurtle` constructor as code generated by an older napi-derive finds
/// it: through `get_class_constructor`, which takes no env and answers with the
/// newest live load on this thread that defined the class.
#[napi]
pub fn legacy_ninja_turtle_constructor(env: &Env) -> Result<Unknown<'_>> {
  let ctor_ref =
    napi::bindgen_prelude::get_class_constructor("NinjaTurtle\0").ok_or_else(|| {
      Error::new(
        Status::GenericFailure,
        "Failed to get constructor of class `NinjaTurtle`",
      )
    })?;
  let mut ctor = std::ptr::null_mut();
  check_status!(
    unsafe { napi::sys::napi_get_reference_value(env.raw(), ctor_ref, &mut ctor) },
    "Failed to get constructor reference of class `NinjaTurtle`"
  )?;
  Ok(unsafe { Unknown::from_raw_unchecked(env.raw(), ctor) })
}
