enum TypeDefKind {
  Const = 'const',
  Enum = 'enum',
  StringEnum = 'string_enum',
  Interface = 'interface',
  Type = 'type',
  Fn = 'fn',
  Struct = 'struct',
  Extends = 'extends',
  Impl = 'impl',
}

interface TypeDefLine {
  kind: TypeDefKind
  name: string
  original_name?: string
  def: string
  def_with_type_import_markers?: string
  extends?: string
  asyncIterator?: [yieldType: string, returnType: string, nextType: string]
  js_doc?: string
  js_mod?: string
  type_imports?: TypeImport[]
}

export interface TypeImport {
  marker?: string
  name: string
  module: string
}

function parseTypeParameters(
  source: string,
): [yieldType: string, returnType: string, nextType: string] | undefined {
  const parameters: string[] = []
  let start = 0
  const depths = {
    angle: 0,
    brace: 0,
    bracket: 0,
    parenthesis: 0,
  }
  let quote: "'" | '"' | '`' | undefined
  let escaped = false

  for (let index = 0; index < source.length; index += 1) {
    const character = source[index]
    if (quote) {
      if (escaped) {
        escaped = false
      } else if (character === '\\') {
        escaped = true
      } else if (character === quote) {
        quote = undefined
      }
      continue
    }

    if (character === "'" || character === '"' || character === '`') {
      quote = character
      continue
    }

    switch (character) {
      case '<':
        depths.angle += 1
        break
      case '>':
        if (source[index - 1] !== '=') {
          depths.angle -= 1
        }
        break
      case '{':
        depths.brace += 1
        break
      case '}':
        depths.brace -= 1
        break
      case '[':
        depths.bracket += 1
        break
      case ']':
        depths.bracket -= 1
        break
      case '(':
        depths.parenthesis += 1
        break
      case ')':
        depths.parenthesis -= 1
        break
      case ',':
        if (Object.values(depths).every((depth) => depth === 0)) {
          parameters.push(source.slice(start, index).trim())
          start = index + 1
        }
        break
    }

    if (Object.values(depths).some((depth) => depth < 0)) {
      return
    }
  }

  if (quote || Object.values(depths).some((depth) => depth !== 0)) {
    return
  }

  parameters.push(source.slice(start).trim())
  if (parameters.length !== 3 || parameters.some((parameter) => !parameter)) {
    return
  }

  return parameters as [string, string, string]
}

function parseIteratorExtends(
  extendsDef: string,
): [yieldType: string, returnType: string, nextType: string] | undefined {
  const match = extendsDef.trim().match(/^Iterator\s*<([\s\S]*)>$/)
  return match ? parseTypeParameters(match[1]) : undefined
}

function parseAsyncGeneratorImpl(
  implDef: string,
): [yieldType: string, returnType: string, nextType: string] | undefined {
  const match = implDef
    .trim()
    .match(/^\[Symbol\.asyncIterator\]\(\):\s*AsyncGenerator\s*<([\s\S]*)>$/)
  return match ? parseTypeParameters(match[1]) : undefined
}

/**
 * Render a single intermediate type-def line as the TypeScript source it
 * should produce in `index.d.ts`.
 *
 * @param line - The intermediate type-def entry to render.
 * @param constEnum - When true, emit numeric and string `#[napi]` enums as
 *   `const enum`. When false (`--no-const-enum`), numeric enums become
 *   regular runtime enums and string enums fall back to a type-only union
 *   unless `runtimeStringEnum` is also true.
 * @param runtimeStringEnum - When true under `--no-const-enum`, emit
 *   `#[napi(string_enum)]` as a runtime enum (`export declare enum`)
 *   instead of a type-only union. No-op when `constEnum` is true.
 * @param ident - Indentation level applied to the rendered output.
 * @param ambient - When true, emit declarations in the ambient form used
 *   inside `declare namespace` blocks (e.g. drop the `declare` keyword).
 */
function prettyPrint(
  line: TypeDefLine,
  constEnum: boolean,
  runtimeStringEnum: boolean,
  ident: number,
  ambient = false,
  asyncGeneratorHelperName?: string,
): string {
  let s = line.js_doc ?? ''
  switch (line.kind) {
    case TypeDefKind.Interface:
      s += `export interface ${line.name} {\n${line.def}\n}`
      break

    case TypeDefKind.Type: {
      const def = line.def.trim()
      s +=
        def.startsWith('|') || def.includes('\n')
          ? `export type ${line.name} =\n${line.def}`
          : `export type ${line.name} = ${def}`
      break
    }

    case TypeDefKind.Enum: {
      const enumName = constEnum ? 'const enum' : 'enum'
      s += `${exportDeclare(ambient)} ${enumName} ${line.name} ${enumBody(line.def)}`
      break
    }

    case TypeDefKind.StringEnum: {
      if (constEnum) {
        s += `${exportDeclare(ambient)} const enum ${line.name} ${enumBody(line.def)}`
      } else if (runtimeStringEnum) {
        s += `${exportDeclare(ambient)} enum ${line.name} ${enumBody(line.def)}`
      } else {
        s += `export type ${line.name} = ${stringEnumToUnion(line.def)}`
      }
      break
    }

    case TypeDefKind.Struct: {
      let classDef = line.def
      let extendsDef = line.extends ? ` extends ${line.extends}` : ''
      let iteratorInterface = ''
      const iteratorTypes = line.extends
        ? parseIteratorExtends(line.extends)
        : undefined
      if (iteratorTypes) {
        // Runtime instances inherit from Iterator.prototype when it exists,
        // but the generated constructor does not extend the global Iterator.
        const [T, TResult, TNext] = iteratorTypes
        const resultType = `${unionPart(TResult)} | undefined`
        classDef +=
          `\n[globalThis.Symbol.iterator](): this` +
          `\nnext(...[value]: [] | [${TNext}]): globalThis.IteratorResult<${T}, ${resultType}>` +
          `\nreturn(...[value]: [] | [${TResult}]): globalThis.IteratorResult<${T}, ${resultType}>` +
          `\nthrow(exception?: unknown): globalThis.IteratorResult<${T}, ${resultType}>`
        extendsDef = ''
        iteratorInterface =
          `\n\nexport interface ${line.name} ` +
          `extends globalThis.Omit<globalThis.IteratorObject<${T}, ${resultType}, ${TNext}>, 'next' | 'return' | 'throw'> {}`
      }
      if (line.asyncIterator) {
        if (!asyncGeneratorHelperName) {
          throw new Error('Async generator helper name was not initialized')
        }
        const [T, TResult, TNext] = line.asyncIterator
        classDef += `\n[globalThis.Symbol.asyncIterator](): globalThis.${asyncGeneratorHelperName}<${line.name}, ${T}, ${TResult}, ${TNext}>`
      }
      s += `${exportDeclare(ambient)} class ${line.name}${extendsDef} ${blockBody(classDef)}`
      s += iteratorInterface
      if (line.original_name && line.original_name !== line.name) {
        s += `\nexport type ${line.original_name} = ${line.name}`
      }
      break
    }

    case TypeDefKind.Fn:
      s += `${exportDeclare(ambient)} ${line.def}`
      break

    case TypeDefKind.Const:
      s += ambient ? line.def : declareExportedConst(line.def)
      break

    default:
      s += line.def
  }

  return correctStringIdent(s, ident)
}

function exportDeclare(ambient: boolean): string {
  if (ambient) {
    return 'export'
  }

  return 'export declare'
}

function blockBody(def: string): string {
  const body = def.trim()
  return body ? `{\n${def}\n}` : '{}'
}

function enumBody(def: string): string {
  const body = def.trim()
  if (!body) {
    return '{}'
  }
  const withTrailingComma = body.endsWith(',') ? def : `${def},`
  return `{\n${withTrailingComma}\n}`
}

function unionPart(type: string): string {
  return type.includes('|') || type.includes('&') || type.includes('=>')
    ? `(${type})`
    : type
}

const EXPORT_CONST_PREFIX = 'export const '

function declareExportedConst(def: string): string {
  return def.startsWith(EXPORT_CONST_PREFIX)
    ? `export declare const ${def.slice(EXPORT_CONST_PREFIX.length)}`
    : def
}

function isWhitespace(character: string): boolean {
  return (
    character === ' ' ||
    character === '\t' ||
    character === '\n' ||
    character === '\r'
  )
}

/**
 * Walk a rust-emitted string-enum body (`Name = 'value', ...`) and collect
 * the initializer literals. Comments and commas inside quotes are skipped
 * by scanning rather than by splitting on `,`.
 */
function stringEnumToUnion(def: string): string {
  const values: string[] = []
  let index = 0

  const eof = () => index >= def.length
  const peek = (offset = 0) => def[index + offset]

  const skipTrivia = () => {
    while (!eof()) {
      const character = peek()
      if (character !== undefined && isWhitespace(character)) {
        index += 1
        continue
      }
      if (character === '/' && peek(1) === '/') {
        index += 2
        while (!eof() && peek() !== '\n') {
          index += 1
        }
        continue
      }
      if (character === '/' && peek(1) === '*') {
        index += 2
        while (!eof() && !(peek() === '*' && peek(1) === '/')) {
          index += 1
        }
        if (!eof()) {
          index += 2
        }
        continue
      }
      return
    }
  }

  const isNameTerminator = (character: string) =>
    isWhitespace(character) ||
    character === '=' ||
    character === ',' ||
    character === "'" ||
    character === '"' ||
    character === '/'

  const parseName = () => {
    if (peek() === "'" || peek() === '"') {
      return parseString() !== undefined
    }
    const character = peek()
    if (
      character === undefined ||
      isNameTerminator(character) ||
      (character >= '0' && character <= '9')
    ) {
      return false
    }
    index += 1
    while (!eof()) {
      const next = peek()
      if (next === undefined || isNameTerminator(next)) {
        break
      }
      index += 1
    }
    return true
  }

  const parseString = () => {
    const quote = peek()
    if (quote !== "'" && quote !== '"') {
      return
    }
    let end = index + 1
    while (end < def.length) {
      if (def[end] === '\\') {
        end += 2
        continue
      }
      if (def[end] === quote) {
        const literal = def.slice(index, end + 1)
        index = end + 1
        return literal
      }
      end += 1
    }
    return
  }

  const parseNumber = () => {
    let end = index
    if (def[end] === '-') {
      end += 1
    }
    const firstDigit = def[end]
    if (firstDigit === undefined || firstDigit < '0' || firstDigit > '9') {
      return
    }
    end += 1
    while (end < def.length) {
      const digit = def[end]
      if (digit === undefined || digit < '0' || digit > '9') {
        break
      }
      end += 1
    }
    const literal = def.slice(index, end)
    index = end
    return literal
  }

  while (!eof()) {
    skipTrivia()
    if (eof()) {
      break
    }
    if (peek() === ',') {
      index += 1
      continue
    }
    if (!parseName()) {
      index += 1
      continue
    }
    skipTrivia()
    if (peek() !== '=') {
      continue
    }
    index += 1
    skipTrivia()
    const value = parseString() ?? parseNumber()
    if (value !== undefined) {
      values.push(value)
    }
  }

  return values.join(' | ')
}

/**
 * Read the napi-derive-emitted intermediate type-def file and render its
 * entries into the `index.d.ts` source string plus the list of names to
 * re-export from `index.js`.
 *
 * @param intermediateTypeFile - Path to the JSONL type-def file produced
 *   by napi-derive (one entry per `#[napi]` item).
 * @param constEnum - See {@link prettyPrint}.
 * @param runtimeStringEnum - See {@link prettyPrint}. Defaults to `false`.
 */
export async function processTypeDef(
  intermediateTypeFile: string,
  constEnum: boolean,
  runtimeStringEnum: boolean = false,
) {
  return processTypeDefs([intermediateTypeFile], constEnum, runtimeStringEnum)
}

export async function processTypeDefs(
  intermediateTypeFiles: string[],
  constEnum: boolean,
  runtimeStringEnum: boolean = false,
  reservedDeclarationText: string = '',
) {
  const exports: string[] = []
  const typeDefs = await Promise.all(
    intermediateTypeFiles.map((file) => readIntermediateTypeFile(file)),
  )
  const typeDefsWithUniqueMarkers = makeTypeImportMarkersUnique(
    typeDefs,
    reservedDeclarationText,
  )
  const typeImports = collectTypeImports(typeDefsWithUniqueMarkers.flat())
  const dtsWithTypeImportMarkers = renderTypeDefs(
    typeDefsWithUniqueMarkers.map((defs) =>
      preprocessTypeDef(preserveTypeImportMarkers(defs)),
    ),
    constEnum,
    runtimeStringEnum,
    exports,
    reservedDeclarationText,
  )
  const dts = rewriteTypeImportReferences(
    dtsWithTypeImportMarkers,
    typeImports,
    false,
  )

  return {
    dts,
    dtsWithTypeImportMarkers,
    exports,
    typeImports,
  }
}

function renderTypeDefs(
  groupedTypeDefs: Map<string, TypeDefLine[]>[],
  constEnum: boolean,
  runtimeStringEnum: boolean,
  exports: string[],
  reservedDeclarationText: string,
): string {
  const topLevelExportNames = new Set<string>()
  for (const groupedDefs of groupedTypeDefs) {
    for (const [namespace, namespaceDefs] of groupedDefs) {
      if (namespace !== TOP_LEVEL_NAMESPACE) {
        if (namespace === 'globalThis') {
          throw new Error(
            'The export name `globalThis` is reserved by NAPI-RS type generation',
          )
        }
        topLevelExportNames.add(namespace)
      }
      for (const def of namespaceDefs) {
        if (def.name === 'globalThis' || def.original_name === 'globalThis') {
          throw new Error(
            'The export name `globalThis` is reserved by NAPI-RS type generation',
          )
        }
        if (namespace === TOP_LEVEL_NAMESPACE) {
          topLevelExportNames.add(def.name)
          if (def.original_name) {
            topLevelExportNames.add(def.original_name)
          }
        }
      }
    }
  }
  const hasIteratorClass = groupedTypeDefs.some((groupedDefs) =>
    Array.from(groupedDefs.values()).some((defs) =>
      defs.some(
        (def) =>
          def.kind === TypeDefKind.Struct &&
          def.extends !== undefined &&
          parseIteratorExtends(def.extends) !== undefined,
      ),
    ),
  )
  const hasAsyncIteratorClass = groupedTypeDefs.some((groupedDefs) =>
    Array.from(groupedDefs.values()).some((defs) =>
      defs.some(
        (def) =>
          def.kind === TypeDefKind.Struct && def.asyncIterator !== undefined,
      ),
    ),
  )
  let asyncGeneratorHelperName = '__NapiRsAsyncGenerator'
  for (
    let suffix = 1;
    topLevelExportNames.has(asyncGeneratorHelperName) ||
    reservedDeclarationText.includes(asyncGeneratorHelperName);
    suffix += 1
  ) {
    asyncGeneratorHelperName = `__NapiRsAsyncGenerator_${suffix}`
  }
  const renderedDefs = groupedTypeDefs
    .map((groupedDefs) =>
      sortBy(Array.from(groupedDefs), [([namespace]) => namespace])
        .map(([namespace, defs]) => {
          if (namespace === TOP_LEVEL_NAMESPACE) {
            return defs
              .map((def) => {
                switch (def.kind) {
                  case TypeDefKind.Const:
                  case TypeDefKind.Enum:
                  case TypeDefKind.StringEnum:
                  case TypeDefKind.Fn:
                  case TypeDefKind.Struct: {
                    exports.push(def.name)
                    if (def.original_name && def.original_name !== def.name) {
                      exports.push(def.original_name)
                    }
                    break
                  }
                  default:
                    break
                }
                return prettyPrint(
                  def,
                  constEnum,
                  runtimeStringEnum,
                  0,
                  false,
                  asyncGeneratorHelperName,
                )
              })
              .join('\n\n')
          } else {
            // A dotted namespace (`a.b`) is nested at runtime, so only its
            // first segment is an export of the binding.
            const exportName = namespace.split('.')[0]
            if (!exports.includes(exportName)) {
              exports.push(exportName)
            }
            let declaration = ''
            declaration += `export declare namespace ${namespace} {\n`
            for (const def of defs) {
              declaration +=
                prettyPrint(
                  def,
                  constEnum,
                  runtimeStringEnum,
                  2,
                  true,
                  asyncGeneratorHelperName,
                ) + '\n'
            }
            declaration += '}'
            return declaration
          }
        })
        .join('\n\n'),
    )
    .join('\n\n')
  const globalDeclarations = []
  if (hasIteratorClass) {
    globalDeclarations.push(ITERATOR_OBJECT_COMPATIBILITY_DECLARATION)
  }
  if (hasAsyncIteratorClass) {
    globalDeclarations.push(asyncGeneratorDeclaration(asyncGeneratorHelperName))
  }
  const dts =
    (globalDeclarations.length
      ? `declare global {\n${globalDeclarations.join('\n\n')}\n}\n\n`
      : '') +
    renderedDefs +
    '\n'
  return dts
}

function makeTypeImportMarkersUnique(
  typeDefGroups: TypeDefLine[][],
  reservedDeclarationText: string,
): TypeDefLine[][] {
  const reservedText = [
    reservedDeclarationText,
    ...typeDefGroups
      .flat()
      .flatMap((def) => [def.def, def.js_doc ?? '', def.name]),
  ].join('\n')
  const allocated = new Set<string>()

  return typeDefGroups.map((defs) =>
    defs.map((def) => {
      const markedDefinition = def.def_with_type_import_markers
      const reallocations: Array<{
        importedName: string
        nextMarker: string
        previousMarker: string
      }> = []
      const typeImports = def.type_imports?.map((typeImport) => {
        if (!typeImport.marker || markedDefinition === undefined) {
          return { ...typeImport }
        }
        const base = typeImport.marker
        let marker = base
        for (
          let suffix = 1;
          allocated.has(marker) || reservedText.includes(marker);
          suffix += 1
        ) {
          marker = `${base}_${suffix}`
        }
        allocated.add(marker)
        reallocations.push({
          importedName: typeImport.name,
          nextMarker: marker,
          previousMarker: typeImport.marker,
        })
        return { ...typeImport, marker }
      })
      return {
        ...def,
        def_with_type_import_markers:
          markedDefinition === undefined
            ? undefined
            : reallocateTypeImportMarkers(
                def.def,
                markedDefinition,
                reallocations,
              ),
        type_imports: typeImports,
      }
    }),
  )
}

function reallocateTypeImportMarkers(
  definition: string,
  markedDefinition: string,
  reallocations: Array<{
    importedName: string
    nextMarker: string
    previousMarker: string
  }>,
) {
  const changedReallocations = reallocations
    .filter(({ nextMarker, previousMarker }) => previousMarker !== nextMarker)
    .sort(
      (left, right) => right.previousMarker.length - left.previousMarker.length,
    )
  if (changedReallocations.length === 0) {
    return markedDefinition
  }

  let definitionOffset = 0
  let markedOffset = 0
  let rewritten = ''
  while (markedOffset < markedDefinition.length) {
    let markerOffset = -1
    let reallocation: (typeof changedReallocations)[number] | undefined
    for (const candidate of changedReallocations) {
      const candidateOffset = markedDefinition.indexOf(
        candidate.previousMarker,
        markedOffset,
      )
      if (
        candidateOffset !== -1 &&
        (markerOffset === -1 || candidateOffset < markerOffset)
      ) {
        markerOffset = candidateOffset
        reallocation = candidate
      }
    }
    if (markerOffset === -1 || reallocation === undefined) {
      break
    }
    const prefix = markedDefinition.slice(markedOffset, markerOffset)
    if (!definition.startsWith(prefix, definitionOffset)) {
      throw new Error(
        `Imported type marker ${reallocation.previousMarker} does not match its declaration`,
      )
    }
    rewritten += prefix
    definitionOffset += prefix.length
    markedOffset = markerOffset + reallocation.previousMarker.length

    if (definition.startsWith(reallocation.previousMarker, definitionOffset)) {
      rewritten += reallocation.previousMarker
      definitionOffset += reallocation.previousMarker.length
    } else if (
      definition.startsWith(reallocation.importedName, definitionOffset)
    ) {
      rewritten += reallocation.nextMarker
      definitionOffset += reallocation.importedName.length
    } else {
      throw new Error(
        `Imported type marker ${reallocation.previousMarker} does not match ${reallocation.importedName} in its declaration`,
      )
    }
  }

  const markedRemainder = markedDefinition.slice(markedOffset)
  const definitionRemainder = definition.slice(definitionOffset)
  if (markedRemainder !== definitionRemainder) {
    throw new Error('Imported type markers leave mismatched declaration text')
  }
  return rewritten + markedRemainder
}

function preserveTypeImportMarkers(defs: TypeDefLine[]): TypeDefLine[] {
  return defs.map((def) => ({
    ...def,
    def: def.def_with_type_import_markers ?? def.def,
  }))
}

function collectTypeImports(defs: TypeDefLine[]): TypeImport[] {
  const imports = new Map<string, TypeImport>()
  for (const typeImport of defs.flatMap((def) => def.type_imports ?? [])) {
    imports.set(
      `${typeImport.marker ?? ''}\0${typeImport.module}\0${typeImport.name}`,
      typeImport,
    )
  }
  return [...imports.values()].sort(
    (left, right) =>
      left.module.localeCompare(right.module) ||
      left.name.localeCompare(right.name) ||
      (left.marker ?? '').localeCompare(right.marker ?? ''),
  )
}

const BUFFER_TYPE_REFERENCE = 'import("buffer").Buffer'
const BUFFER_HERITAGE_ALIAS = '__NapiRsBuffer'
const IN_MEMORY_DECLARATION_FILE = '/__napi_rs_typegen__.d.ts'

export function rewriteTypeImportReferences(
  source: string,
  typeImports: TypeImport[],
  inlineImports: boolean,
): string {
  const markerImports = new Map<string, TypeImport>()
  for (const typeImport of typeImports) {
    const { marker } = typeImport
    if (marker) {
      markerImports.set(marker, typeImport)
    }
  }
  const rewriteUnboundBuffer = inlineImports && source.includes('Buffer')
  if (markerImports.size === 0 && !rewriteUnboundBuffer) {
    return source
  }

  const typeScript = loadTypeScript()
  const { program, sourceFile } = createDeclarationProgram(source)
  const checker = rewriteUnboundBuffer ? program.getTypeChecker() : undefined
  let bufferHeritageAlias: string | undefined
  const getBufferHeritageAlias = () => {
    bufferHeritageAlias ??= createCollisionSafeIdentifier(
      typeScript,
      sourceFile,
      BUFFER_HERITAGE_ALIAS,
    )
    return bufferHeritageAlias
  }
  const replacements: Array<{
    end: number
    replacement: string
    start: number
  }> = []

  const visit = (node: import('typescript').Node) => {
    if (typeScript.isIdentifier(node)) {
      const markerImport = markerImports.get(node.text)
      if (
        markerImport !== undefined &&
        typeImportReferenceMeaning(typeScript, node) !== undefined
      ) {
        const useBufferHeritageAlias =
          inlineImports &&
          markerImport.module === 'buffer' &&
          markerImport.name === 'Buffer' &&
          isHeritageReference(typeScript, node)
        replacements.push({
          start: node.getStart(sourceFile),
          end: node.end,
          replacement: inlineImports
            ? useBufferHeritageAlias
              ? getBufferHeritageAlias()
              : `import(${JSON.stringify(markerImport.module)}).${markerImport.name}`
            : markerImport.name,
        })
      } else if (
        checker !== undefined &&
        node.text === 'Buffer' &&
        isUnboundBufferReference(typeScript, checker, node)
      ) {
        replacements.push({
          start: node.getStart(sourceFile),
          end: node.end,
          replacement: isHeritageReference(typeScript, node)
            ? getBufferHeritageAlias()
            : BUFFER_TYPE_REFERENCE,
        })
      }
    }
    typeScript.forEachChild(node, visit)
  }
  visit(sourceFile)

  let rewritten = source
  for (const replacement of replacements.reverse()) {
    rewritten =
      rewritten.slice(0, replacement.start) +
      replacement.replacement +
      rewritten.slice(replacement.end)
  }
  if (bufferHeritageAlias) {
    rewritten = appendAliasedImport(
      rewritten,
      'buffer',
      'Buffer',
      bufferHeritageAlias,
    )
  }
  return rewritten
}

export function rebaseDeclarationSpecifiers(
  source: string,
  sourcePath: string,
  destinationPath: string,
): string {
  const references = collectRelativeDeclarationSpecifierReferences(source)
  const replacements: Array<{
    end: number
    replacement: string
    start: number
  }> = []

  for (const reference of references) {
    const absoluteTarget = resolve(dirname(sourcePath), reference.specifier)
    let rebased = relative(dirname(destinationPath), absoluteTarget).replaceAll(
      '\\',
      '/',
    )
    if (!rebased.startsWith('.')) {
      rebased = `./${rebased}`
    }
    replacements.push({
      start: reference.start,
      end: reference.end,
      replacement: rebased,
    })
  }

  let rebasedSource = source
  for (const replacement of replacements
    .filter(
      (replacement, index, all) =>
        all.findIndex(
          (candidate) =>
            candidate.start === replacement.start &&
            candidate.end === replacement.end,
        ) === index,
    )
    .sort((left, right) => right.start - left.start)) {
    rebasedSource =
      rebasedSource.slice(0, replacement.start) +
      replacement.replacement +
      rebasedSource.slice(replacement.end)
  }
  return rebasedSource
}

interface DeclarationSpecifierReference {
  end: number
  specifier: string
  start: number
}

export function collectRelativeDeclarationSpecifiers(source: string): string[] {
  return [
    ...new Set(
      collectRelativeDeclarationSpecifierReferences(source).map(
        ({ specifier }) => specifier,
      ),
    ),
  ]
}

/**
 * The first construct in `source` a CommonJS declaration file cannot carry,
 * or `undefined` when copying `source` into a `.d.cts` is honest.
 *
 * A `.d.cts` is read under `require` module-resolution mode, so a declaration
 * that means one thing in an ESM file can mean another — or be a syntax error
 * — once it lands there. The generated typedef needs none of those forms: its
 * imports name packages or `node:` builtins, and everything it exports is a
 * named `export declare`. A `--dts-header` can carry any declaration a module
 * package can write, though, and silently copying one that resolves
 * differently produces a `.d.cts` describing a module the loader is not.
 * Those sources keep refusing, with the offending construct named, so the
 * header can be fixed or `--dts` pointed at a `.d.cts` source instead.
 *
 * What refuses, and why:
 *
 * - `export default`, in any of its spellings — `export default x`,
 *   `export default class`/`function`/`interface`/`enum`/`namespace`,
 *   `export { x as default }`, `export * as default`. In a `.d.cts` `default`
 *   is `module.exports.default` — a property the generated loader never
 *   assigns — not the whole-callable shape a default export is in ESM. Inside
 *   a `declare module` block `export default` describes that module's own
 *   shape and carries over honestly, so only top-level defaults refuse.
 * - A relative specifier that can land on a mode-dependent declaration:
 *   `.js`-family spellings (`.js`, `.jsx`, `.ts`, `.tsx`) or extensionless
 *   ones, which resolve `.d.cts`-first under `require` mode and
 *   `.d.mts`-first under `import` mode — possibly a different file, and
 *   certainly a different interpretation of the file they find. Explicit
 *   module-format extensions (`.mjs`, `.mts`, `.cjs`, `.cts`) and non-script
 *   targets (`.json`, `.wasm`, `.node`, assets) resolve identically either
 *   way. Bare specifiers (`buffer`, `node:stream/web`, package names) are
 *   allowed — a dual-condition package's `types` entry can still diverge
 *   (`import` vs `require` condition), but refusing them would defeat the
 *   derivation: the generated typedef's own imports are all bare.
 * - `with { … }` attributes on a runtime `import`/`export … from` statement:
 *   TS2856 in a `.cts` file. Type-only statements may keep theirs, and a
 *   `resolution-mode` attribute pins the specifier to one mode — either way
 *   the same mode `.d.cts` or the source's own — so it is honest again.
 *
 * Everything else — `export declare`, interfaces, enums, namespaces,
 * `export =`, `declare global`, `/// <reference path>` — reads the same on
 * both sides. One deliberate gap: `import('…')` types inside JSDoc comments
 * are not scanned — they need a separate JSDoc parse for a source class the
 * generator never emits.
 */
export function commonJsDeclarationBarrier(source: string): string | undefined {
  const typeScript = loadTypeScript()
  const sourceFile = parseDeclarationFile(source)

  const specifierBarrier = (
    literal: import('typescript').StringLiteralLike,
  ): string | undefined => {
    if (!literal.text.startsWith('.')) {
      return undefined
    }
    const extension = parse(literal.text).ext.toLowerCase()
    if (
      extension !== '' &&
      !['.js', '.jsx', '.ts', '.tsx'].includes(extension)
    ) {
      return undefined
    }
    return `a relative '${literal.text}' specifier`
  }

  const hasResolutionMode = (
    attributes: import('typescript').ImportAttributes | undefined,
  ) =>
    attributes?.elements.some(
      (element) =>
        element.name.text === 'resolution-mode' &&
        typeScript.isStringLiteral(element.value) &&
        (element.value.text === 'import' || element.value.text === 'require'),
    ) === true

  const hasDefaultModifier = (node: Node) =>
    typeScript.canHaveModifiers(node) === true &&
    typeScript
      .getModifiers(node)
      ?.some(
        (modifier) => modifier.kind === typeScript.SyntaxKind.DefaultKeyword,
      ) === true

  const isTypeOnlyStatement = (
    node:
      | import('typescript').ImportDeclaration
      | import('typescript').ExportDeclaration,
  ) =>
    typeScript.isImportDeclaration(node)
      ? node.importClause?.isTypeOnly === true
      : node.isTypeOnly === true

  let barrier: string | undefined
  const visit = (node: Node, insideModuleDeclaration: boolean): void => {
    if (barrier !== undefined) {
      return
    }
    if (!insideModuleDeclaration && hasDefaultModifier(node)) {
      barrier = 'an `export default` declaration'
      return
    }
    if (typeScript.isModuleDeclaration(node)) {
      if (typeScript.isStringLiteralLike(node.name)) {
        barrier = specifierBarrier(node.name)
      }
      if (barrier === undefined) {
        // A `declare module`/`declare global` block's statements describe that
        // module's own shape, so a `default` export inside one is honest; its
        // specifiers still resolve relative to this file.
        typeScript.forEachChild(node, (child) => visit(child, true))
      }
      return
    }
    if (
      typeScript.isImportDeclaration(node) ||
      typeScript.isExportDeclaration(node)
    ) {
      if (node.attributes !== undefined && !isTypeOnlyStatement(node)) {
        barrier = '`with` attributes on a runtime module statement'
        return
      }
      if (
        node.moduleSpecifier !== undefined &&
        typeScript.isStringLiteralLike(node.moduleSpecifier) &&
        !hasResolutionMode(node.attributes)
      ) {
        barrier = specifierBarrier(node.moduleSpecifier)
        if (barrier !== undefined) {
          return
        }
      }
      if (
        !insideModuleDeclaration &&
        typeScript.isExportDeclaration(node) &&
        node.exportClause !== undefined &&
        ((typeScript.isNamedExports(node.exportClause) &&
          node.exportClause.elements.some(
            (element) => element.name.text === 'default',
          )) ||
          (typeScript.isNamespaceExport(node.exportClause) &&
            node.exportClause.name.text === 'default'))
      ) {
        barrier = 'a `default` re-export'
      }
      return
    }
    if (typeScript.isImportEqualsDeclaration(node)) {
      if (
        typeScript.isExternalModuleReference(node.moduleReference) &&
        typeScript.isStringLiteralLike(node.moduleReference.expression)
      ) {
        barrier = specifierBarrier(node.moduleReference.expression)
      }
      return
    }
    if (typeScript.isExportAssignment(node)) {
      if (node.isExportEquals !== true && !insideModuleDeclaration) {
        barrier = 'an `export default` declaration'
      }
      return
    }
    if (typeScript.isImportTypeNode(node)) {
      if (
        typeScript.isLiteralTypeNode(node.argument) &&
        typeScript.isStringLiteralLike(node.argument.literal) &&
        !hasResolutionMode(node.attributes)
      ) {
        barrier = specifierBarrier(node.argument.literal)
      }
      // `import('pkg').T<import('./x.js').U>` nests another specifier in the
      // type arguments — keep descending.
      if (barrier === undefined) {
        typeScript.forEachChild(node, (child) =>
          visit(child, insideModuleDeclaration),
        )
      }
      return
    }
    if (
      typeScript.isCallExpression(node) &&
      node.arguments.length >= 1 &&
      typeScript.isStringLiteralLike(node.arguments[0]) &&
      (node.expression.kind === typeScript.SyntaxKind.ImportKeyword ||
        (typeScript.isIdentifier(node.expression) &&
          node.expression.text === 'require'))
    ) {
      barrier = specifierBarrier(node.arguments[0])
      return
    }
    typeScript.forEachChild(node, (child) =>
      visit(child, insideModuleDeclaration),
    )
  }
  for (const statement of sourceFile.statements) {
    visit(statement, false)
  }
  if (barrier === undefined) {
    // `/// <reference types>` resolves through module resolution — a relative
    // name can diverge the same way a relative specifier can. `path`
    // references are file-path resolution and carry over honestly.
    for (const reference of typeScript.preProcessFile(source, true, true)
      .typeReferenceDirectives) {
      if (
        reference.fileName.startsWith('.') &&
        reference.resolutionMode === undefined
      ) {
        barrier = `a relative '/// <reference types="${reference.fileName}" />' directive`
        break
      }
    }
  }
  return barrier
}

function collectRelativeDeclarationSpecifierReferences(
  source: string,
): DeclarationSpecifierReference[] {
  const typeScript = loadTypeScript()
  const sourceFile = typeScript.createSourceFile(
    IN_MEMORY_DECLARATION_FILE,
    source,
    typeScript.ScriptTarget.Latest,
    true,
    typeScript.ScriptKind.TS,
  )
  const references: DeclarationSpecifierReference[] = []
  const addStringLiteral = (node: import('typescript').StringLiteralLike) => {
    if (!node.text.startsWith('.')) {
      return
    }
    references.push({
      start: node.getStart(sourceFile) + 1,
      end: node.end - 1,
      specifier: node.text,
    })
  }
  const visit = (node: import('typescript').Node) => {
    if (
      (typeScript.isImportDeclaration(node) ||
        typeScript.isExportDeclaration(node)) &&
      node.moduleSpecifier &&
      typeScript.isStringLiteralLike(node.moduleSpecifier)
    ) {
      addStringLiteral(node.moduleSpecifier)
    } else if (
      typeScript.isImportTypeNode(node) &&
      typeScript.isLiteralTypeNode(node.argument) &&
      typeScript.isStringLiteralLike(node.argument.literal)
    ) {
      addStringLiteral(node.argument.literal)
    } else if (
      typeScript.isModuleDeclaration(node) &&
      typeScript.isStringLiteralLike(node.name)
    ) {
      addStringLiteral(node.name)
    } else if (
      typeScript.isExternalModuleReference(node) &&
      node.expression &&
      typeScript.isStringLiteralLike(node.expression)
    ) {
      addStringLiteral(node.expression)
    } else if (
      typeScript.isCallExpression(node) &&
      node.arguments.length >= 1 &&
      typeScript.isStringLiteralLike(node.arguments[0]) &&
      (node.expression.kind === typeScript.SyntaxKind.ImportKeyword ||
        (typeScript.isIdentifier(node.expression) &&
          node.expression.text === 'require'))
    ) {
      addStringLiteral(node.arguments[0])
    }
    typeScript.forEachChild(node, visit)
  }
  visit(sourceFile)

  const preprocessed = typeScript.preProcessFile(source, true, true)
  for (const reference of [
    ...preprocessed.referencedFiles,
    ...preprocessed.typeReferenceDirectives,
  ]) {
    if (reference.fileName.startsWith('.')) {
      references.push({
        start: reference.pos,
        end: reference.end,
        specifier: reference.fileName,
      })
    }
  }

  return references
    .filter(
      (reference, index, all) =>
        all.findIndex(
          (candidate) =>
            candidate.start === reference.start &&
            candidate.end === reference.end,
        ) === index,
    )
    .sort((left, right) => left.start - right.start)
}

function createCollisionSafeIdentifier(
  typeScript: TypeScriptModule,
  sourceFile: SourceFile,
  baseName: string,
): string {
  const identifiers = new Set<string>()
  const visit = (node: import('typescript').Node) => {
    if (typeScript.isIdentifier(node)) {
      identifiers.add(node.text)
    }
    typeScript.forEachChild(node, visit)
  }
  visit(sourceFile)

  let identifier = baseName
  let suffix = 1
  while (identifiers.has(identifier)) {
    identifier = `${baseName}_${suffix}`
    suffix += 1
  }
  return identifier
}

function isHeritageReference(
  typeScript: TypeScriptModule,
  identifier: Identifier,
): boolean {
  const parent = identifier.parent
  return (
    typeScript.isExpressionWithTypeArguments(parent) &&
    parent.expression === identifier &&
    typeScript.isHeritageClause(parent.parent)
  )
}

function isUnboundBufferReference(
  typeScript: TypeScriptModule,
  checker: import('typescript').TypeChecker,
  identifier: Identifier,
): boolean {
  const meaning = typeImportReferenceMeaning(typeScript, identifier)
  return (
    meaning !== undefined &&
    checker.resolveName(identifier.text, identifier, meaning, false) ===
      undefined
  )
}

function typeImportReferenceMeaning(
  typeScript: TypeScriptModule,
  identifier: Identifier,
): SymbolFlags | undefined {
  let entityName: EntityName = identifier
  while (
    typeScript.isQualifiedName(entityName.parent) &&
    entityName.parent.left === entityName
  ) {
    entityName = entityName.parent
  }

  const parent = entityName.parent
  if (
    typeScript.isTypeReferenceNode(parent) &&
    parent.typeName === entityName
  ) {
    return typeScript.SymbolFlags.Type
  }
  if (typeScript.isTypeQueryNode(parent) && parent.exprName === entityName) {
    return typeScript.SymbolFlags.Value
  }
  if (
    typeScript.isExpressionWithTypeArguments(parent) &&
    parent.expression === entityName &&
    typeScript.isHeritageClause(parent.parent)
  ) {
    const heritageClause = parent.parent
    const declaration = heritageClause.parent
    return heritageClause.token === typeScript.SyntaxKind.ExtendsKeyword &&
      (typeScript.isClassDeclaration(declaration) ||
        typeScript.isClassExpression(declaration))
      ? typeScript.SymbolFlags.Value
      : typeScript.SymbolFlags.Type
  }
}

/**
 * A program over one already-parsed declaration file and nothing else.
 *
 * `noLib` and `noResolve` are the point, not an optimization: the answers a
 * caller takes from this program have to depend on the source alone, never on
 * what happens to sit next to the output directory. Nothing outside the file
 * is loaded, so an unresolved import stays unresolved rather than resolving
 * differently from one machine to the next.
 */
function programOverDeclarationSource(
  sourceFile: SourceFile,
  source: string,
): import('typescript').Program {
  const typeScript = loadTypeScript()
  const options: CompilerOptions = {
    module: typeScript.ModuleKind.ESNext,
    noLib: true,
    noResolve: true,
    skipLibCheck: true,
    target: typeScript.ScriptTarget.Latest,
    types: [],
  }
  const host: CompilerHost = {
    fileExists: (fileName) => fileName === IN_MEMORY_DECLARATION_FILE,
    getCanonicalFileName: (fileName) => fileName,
    getCurrentDirectory: () => '/',
    getDefaultLibFileName: () => '',
    getDirectories: () => [],
    getNewLine: () => '\n',
    getSourceFile: (fileName) =>
      fileName === IN_MEMORY_DECLARATION_FILE ? sourceFile : undefined,
    readFile: (fileName) =>
      fileName === IN_MEMORY_DECLARATION_FILE ? source : undefined,
    useCaseSensitiveFileNames: () => true,
    writeFile: () => {},
  }
  return typeScript.createProgram({
    rootNames: [IN_MEMORY_DECLARATION_FILE],
    options,
    host,
  })
}

function createDeclarationProgram(source: string): {
  program: import('typescript').Program
  sourceFile: SourceFile
} {
  const typeScript = loadTypeScript()
  const sourceFile = parseDeclarationFile(source)
  const program = programOverDeclarationSource(sourceFile, source)
  const diagnostics = program.getSyntacticDiagnostics(sourceFile)
  if (diagnostics.length > 0) {
    throwDeclarationDiagnostics(typeScript, sourceFile, diagnostics)
  }
  return { program, sourceFile }
}

/**
 * Parse a declaration source without judging it. Unlike
 * {@link parseDeclarationSource}, a syntax error somewhere else in the file is
 * no reason to refuse to answer a question about it: this runs over whatever a
 * project put in its `--dts-header` and over declaration files kept from
 * earlier builds.
 */
function parseDeclarationFile(source: string): SourceFile {
  const typeScript = loadTypeScript()
  return typeScript.createSourceFile(
    IN_MEMORY_DECLARATION_FILE,
    source,
    typeScript.ScriptTarget.Latest,
    true,
    typeScript.ScriptKind.TS,
  )
}

function throwDeclarationDiagnostics(
  typeScript: TypeScriptModule,
  sourceFile: SourceFile,
  diagnostics: readonly Diagnostic[],
): never {
  const messages = diagnostics.slice(0, 3).map((diagnostic) => {
    const message = typeScript.flattenDiagnosticMessageText(
      diagnostic.messageText,
      '\n',
    )
    if (diagnostic.start === undefined) {
      return message
    }
    const { character, line } = sourceFile.getLineAndCharacterOfPosition(
      diagnostic.start,
    )
    return `${line + 1}:${character + 1} ${message}`
  })
  throw new Error(`Failed to parse declaration source:\n${messages.join('\n')}`)
}

function decodeStructuralNewlines(source: string): string {
  let output = ''
  let index = 0

  while (index < source.length) {
    const character = source[index]
    if (character === "'" || character === '"' || character === '`') {
      const quote = character
      output += character
      index += 1
      while (index < source.length) {
        const current = source[index]
        output += current
        index += 1
        if (current === '\\' && index < source.length) {
          output += source[index]
          index += 1
        } else if (current === quote) {
          break
        }
      }
      continue
    }
    if (character === '/' && source[index + 1] === '/') {
      const end = source.indexOf('\n', index + 2)
      if (end === -1) {
        output += source.slice(index)
        break
      }
      output += source.slice(index, end)
      index = end
      continue
    }
    if (character === '/' && source[index + 1] === '*') {
      const end = source.indexOf('*/', index + 2)
      if (end === -1) {
        output += source.slice(index)
        break
      }
      output += source.slice(index, end + 2)
      index = end + 2
      continue
    }
    if (character === '\\' && source[index + 1] === 'n') {
      output += '\n'
      index += 2
      continue
    }
    output += character
    index += 1
  }
  return output
}

export function appendTypeImports(
  source: string,
  typeImports: TypeImport[],
): string {
  const typeScript = loadTypeScript()
  const parsed = parseDeclarationSource(source)
  const missingImports = typeImports.filter(
    (typeImport) => !hasNamedImport(parsed.statements, typeImport),
  )
  if (missingImports.length === 0) {
    return source
  }

  const importsByModule = new Map<string, string[]>()
  for (const { module, name } of missingImports) {
    const names = importsByModule.get(module) ?? []
    names.push(name)
    importsByModule.set(module, names)
  }
  const newline = source.includes('\r\n') ? '\r\n' : '\n'
  const importSource = [...importsByModule]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([module, names]) =>
        `import type { ${[...new Set(names)].sort().join(', ')} } from ${JSON.stringify(module)}`,
    )
    .join(newline)
  const importDeclarations = parsed.statements.filter(
    typeScript.isImportDeclaration,
  )
  const insertionOffset = importDeclarations.length
    ? endOfLine(source, importDeclarations.at(-1)!.end)
    : leadingDeclarationPreambleEnd(source, parsed)

  return insertDeclarationSource(source, insertionOffset, importSource, newline)
}

function appendAliasedImport(
  source: string,
  module: string,
  importedName: string,
  localName: string,
): string {
  const typeScript = loadTypeScript()
  const parsed = parseDeclarationSource(source)
  const newline = source.includes('\r\n') ? '\r\n' : '\n'
  const importDeclarations = parsed.statements.filter(
    typeScript.isImportDeclaration,
  )
  const insertionOffset = importDeclarations.length
    ? endOfLine(source, importDeclarations.at(-1)!.end)
    : leadingDeclarationPreambleEnd(source, parsed)
  return insertDeclarationSource(
    source,
    insertionOffset,
    `import { ${importedName} as ${localName} } from ${JSON.stringify(module)}`,
    newline,
  )
}

export function removeNodeStreamWebTypeImports(source: string): string {
  const typeScript = loadTypeScript()
  const parsed = parseDeclarationSource(source)
  const removals: Array<{ start: number; end: number }> = []

  for (const statement of parsed.statements) {
    if (
      !typeScript.isImportDeclaration(statement) ||
      !typeScript.isStringLiteral(statement.moduleSpecifier) ||
      statement.moduleSpecifier.text !== 'node:stream/web'
    ) {
      continue
    }
    const importClause = statement.importClause
    const namedBindings = importClause?.namedBindings
    const unaliasedNamedTypeImports =
      importClause !== undefined &&
      namedBindings !== undefined &&
      typeScript.isNamedImports(namedBindings) &&
      namedBindings.elements.length > 0 &&
      namedBindings.elements.every(
        (specifier) =>
          (importClause.isTypeOnly || specifier.isTypeOnly) &&
          specifier.propertyName === undefined,
      )
    if (!unaliasedNamedTypeImports) {
      throw new Error(
        'Threadless declaration headers may only import unaliased types from node:stream/web so DOM globals can replace them',
      )
    }
    removals.push(
      expandToDeclarationLine(
        source,
        statement.getStart(parsed),
        statement.end,
      ),
    )
  }

  let result = source
  for (const removal of removals.reverse()) {
    result = result.slice(0, removal.start) + result.slice(removal.end)
  }
  return result
}

export function rewriteUnboundNodeGlobalTypeQueries(source: string): string {
  if (!source.includes('global')) {
    return source
  }
  const typeScript = loadTypeScript()
  const { program, sourceFile } = createDeclarationProgram(source)
  const checker = program.getTypeChecker()
  const replacements: Array<{ start: number; end: number }> = []
  const visit = (node: import('typescript').Node) => {
    if (
      typeScript.isIdentifier(node) &&
      node.text === 'global' &&
      typeScript.isTypeQueryNode(node.parent) &&
      node.parent.exprName === node &&
      checker.resolveName(
        node.text,
        node,
        typeScript.SymbolFlags.Value,
        false,
      ) === undefined
    ) {
      replacements.push({
        start: node.getStart(sourceFile),
        end: node.end,
      })
    }
    typeScript.forEachChild(node, visit)
  }
  visit(sourceFile)

  let rewritten = source
  for (const replacement of replacements.reverse()) {
    rewritten =
      rewritten.slice(0, replacement.start) +
      'globalThis' +
      rewritten.slice(replacement.end)
  }
  return rewritten
}

/**
 * One top-level `export … const|let|var <name>` found by
 * {@link scanExportedName}.
 */
export interface ExportedVariableDeclaration {
  /**
   * Where the declaration block starts: the doc comment written directly above
   * the statement when there is one, so replacing the span swaps the comment
   * with it instead of stranding it.
   */
  start: number
  /**
   * Just past the statement, the statement's own `;` included and trailing
   * trivia excluded. A caller that replaces `[start, end)` therefore has to
   * put that terminator back, or whatever followed on the same line runs
   * straight into the replacement.
   */
  end: number
  /**
   * Where this declarator starts: the name, without the `export declare const`
   * in front of it.
   */
  declaratorStart: number
  /** Just past this declarator, before any `,` that separates it from a sibling. */
  declaratorEnd: number
  /**
   * How many names the statement declares in all. More than one and
   * `[start, end)` covers names besides this one, so replacing that span would
   * delete them.
   */
  declaratorCount: number
  /** The type annotation as written, or `undefined` when there is none. */
  type?: string
}

/** What {@link scanExportedName} reads out of one declaration source. */
export interface ExportedNameScan {
  /**
   * Whether the file exports by assignment (`export = x`) at the top level,
   * which is what a build without `napi-derive`'s `type-def` feature emits.
   * Such a file cannot carry a named export at all.
   *
   * `export default x` parses as the same node and does not count: only
   * `isExportEquals` does.
   */
  exportsByAssignment: boolean
  /**
   * Whether this source already binds `name` in a way that leaves no room for
   * an added `export declare const name` — as an export, or as a top-level
   * declaration the const would redeclare.
   *
   * Not simply "is it exported": TypeScript merges a value with a declaration
   * that lives only in type space, and a caller that backed off there would
   * take away typed access to a real runtime export (TS2693 at every value
   * use) while preventing no collision at all. So an exported `type`,
   * `interface` or non-instantiated namespace is *not* an owner.
   *
   * Which leaves the question of what "value space" means for every shape a
   * declaration file can take, and that is TypeScript's question to answer,
   * not this CLI's — see {@link scanExportedName}. An owner is an export the
   * checker gives `SymbolFlags.Value` (a variable, `function`, `class`,
   * `enum`, an instantiated namespace — instantiated by the binder's rules,
   * which count an aliased member such as `export import x = …` that hand-
   * written recursion over the body kept missing) or `SymbolFlags.Alias`
   * (every `export { … }` clause, its `export type { … }` and
   * `export * as name from '…'` forms, and `export import name = …`; an alias
   * collides with a local declaration of the name however it is spelled —
   * TS2323, TS2440).
   *
   * The same two flags settle a binding that is not exported at all: a
   * declaration file that is not a module has no export table, and its
   * top-level `declare const name` is a global the generated export would
   * redeclare; inside a module an `import name = …` the file keeps to itself
   * conflicts too. A top-level `type` or `interface` does not, in either
   * place — and neither does a name the file puts in the *global* scope
   * rather than its own, through a `declare global { … }` member or the UMD
   * name of `export as namespace name`: the added export shadows it instead
   * of colliding with it.
   *
   * `export default` binds `default` rather than a name, and
   * `export * from '…'` is left unresolved on purpose, so it names nothing
   * here; neither counts.
   */
  ownsName: boolean
  /**
   * Whether the file was bound to answer {@link ownsName}, or whether the
   * source was settled without it.
   *
   * Binding is skipped only for a source that can spell no such name at all —
   * see {@link scanExportedName}. Nothing in this CLI branches on it: it is
   * here so a test can hold that shortcut in place without timing anything,
   * which is the only way to notice it has quietly stopped applying.
   */
  checked: boolean
  /**
   * The exported variable statements that declare `name`, in source order.
   * Only these carry a span a caller can rewrite; the other export forms above
   * have no declaration here to replace.
   */
  declarations: ExportedVariableDeclaration[]
}

/**
 * How a declaration source exports `name`, and whether it exports by
 * assignment instead.
 *
 * Parsed rather than pattern-matched, because a declaration file spells both
 * in places that are not an export of it. `napi-derive` copies a crate's
 * `js_doc` through verbatim, so a doc comment can name either; a
 * `--dts-header` may carry a commented-out example of the declaration or of
 * `export = binding`, or a member of a `declare namespace` / `declare module`
 * block, which is an export of that block and not of the file. Importing any
 * of those yields TS2305, and a commented-out `export =` is not an export
 * assignment at all.
 *
 * Ownership is decided by TypeScript's own binder rather than by a list of
 * shapes this CLI enumerates. Every attempt at the list missed something —
 * a namespace export clause, an `export import` member, an alias nested one
 * level deeper — because the question is really "what does this file export,
 * and in which declaration space", and only the checker knows. So the file is
 * bound and {@link ExportedNameScan.ownsName} is read off the export symbol's
 * flags.
 *
 * The syntax is still what finds the rewritable declaration and its span, and
 * one parse serves both: the program is built over the source file parsed
 * here, so binding costs no second parse.
 */
export function scanExportedName(
  source: string,
  name: string,
): ExportedNameScan {
  const typeScript = loadTypeScript()
  const sourceFile = parseDeclarationFile(source)
  const declarations: ExportedVariableDeclaration[] = []
  let exportsByAssignment = false
  for (const statement of sourceFile.statements) {
    if (typeScript.isExportAssignment(statement)) {
      // `export = x`. `export default x` is the same node without the flag,
      // and it binds `default`, never `name`.
      exportsByAssignment ||= statement.isExportEquals === true
      continue
    }
    // Only an exported variable statement leaves a declaration a caller can
    // rewrite in place. Every other owner is found through the checker below,
    // which has no span to offer and needs none.
    if (
      !typeScript.isVariableStatement(statement) ||
      !statement.modifiers?.some(
        (modifier) => modifier.kind === typeScript.SyntaxKind.ExportKeyword,
      )
    ) {
      continue
    }
    for (const declaration of statement.declarationList.declarations) {
      if (
        !typeScript.isIdentifier(declaration.name) ||
        declaration.name.text !== name
      ) {
        continue
      }
      declarations.push({
        start: declarationBlockStart(source, sourceFile, statement),
        end: statement.end,
        declaratorStart: declaration.getStart(sourceFile),
        declaratorEnd: declaration.end,
        declaratorCount: statement.declarationList.declarations.length,
        type: declaration.type?.getText(sourceFile),
      })
      break
    }
  }
  const { ownsName, checked } = sourceBindsName(sourceFile, source, name)
  return { exportsByAssignment, ownsName, checked, declarations }
}

/**
 * Whether anything in this source already binds `name` where a generated
 * `export declare const name` would land — as an export of the file, or as a
 * declaration at its top level that the const would redeclare — and whether
 * the file had to be bound to find out.
 *
 * Both questions are the checker's, and both are answered off the same
 * program. See {@link ExportedNameScan.ownsName}.
 */
function sourceBindsName(
  sourceFile: SourceFile,
  source: string,
  name: string,
): { ownsName: boolean; checked: boolean } {
  const typeScript = loadTypeScript()
  // A binding of `name` in this file has to spell it here — but it need not
  // spell it in the characters the name is made of. An identifier may write
  // any of them as a `\uXXXX` or `\u{…}` escape; a string-literal export name
  // (`export { x as "…" }`) may use `\xXX` as well, and may be broken across
  // lines with a backslash-newline continuation. TypeScript resolves every one
  // of those to the same name where a text search sees nothing. Enumerating
  // the escapes is the game that was already lost once, so the shortcut asks
  // for less: a source carrying neither the name nor a backslash *anywhere*
  // cannot spell it, and that is what almost every header is. Everything else
  // goes to the checker, which has always been able to say. The other form a
  // text search would miss is `export * from '…'`, which the program below
  // leaves unresolved by design, so nothing is skipped there either.
  if (!source.includes(name) && !source.includes('\\')) {
    return { ownsName: false, checked: false }
  }
  // A value or an alias is what a `const` of the same name cannot be written
  // beside; a type-only declaration is what it merges with.
  const meaning = typeScript.SymbolFlags.Alias | typeScript.SymbolFlags.Value
  const checker = programOverDeclarationSource(
    sourceFile,
    source,
  ).getTypeChecker()
  const moduleSymbol = checker.getSymbolAtLocation(sourceFile)
  const exported =
    moduleSymbol === undefined
      ? undefined
      : checker
          .getExportsOfModule(moduleSymbol)
          .find((symbol) => symbol.name === name)
  if (exported !== undefined && (exported.flags & meaning) !== 0) {
    return { ownsName: true, checked: true }
  }
  // Not every binding that collides is an export. A declaration file that is
  // not a module has no export table at all, and its top-level `declare const`
  // is a global the generated export would redeclare (TS2451, TS2395). Inside
  // a module, an `import name = …` kept to the file is likewise no export and
  // still conflicts (TS2440). Ambient declaration files put most top-level
  // declarations in the export table by themselves, so these are the leftovers
  // rather than the common case — but they are the ones a rule written around
  // exports alone would miss.
  //
  // Scoped at the source file, so a binding nested inside a namespace or a
  // function body is correctly none of this file's business, and filtered to
  // the declarations that bind in this file's own scope — see
  // {@link declaresInFileScope}.
  return {
    ownsName: checker
      .getSymbolsInScope(sourceFile, meaning)
      .some(
        (symbol) =>
          symbol.name === name &&
          symbol.declarations?.some((declaration) =>
            declaresInFileScope(typeScript, declaration, sourceFile),
          ) === true,
      ),
    checked: true,
  }
}

/**
 * Whether `declaration` binds its name in `sourceFile`'s own scope — the scope
 * a generated `export declare const` would land in.
 *
 * `getSymbolsInScope` answers what is *visible* at a location, and the global
 * scope is visible everywhere, so a name a file declares into that scope comes
 * back from it while colliding with nothing the file itself adds. Written here
 * is therefore not enough; written here *and at this file's top level* is the
 * question:
 *
 * - A `declare global { … }` member is a global, reached through a
 *   `ModuleDeclaration`. A module-scoped `export declare const` of the same
 *   name shadows it rather than redeclaring it. The members of an ambient
 *   `declare module '…'` block and of a `declare namespace` belong to that
 *   module or namespace instead of to the file; the checker already keeps
 *   those out of scope here, and the same walk covers them without depending
 *   on that.
 * - `export as namespace name` declares a UMD global for script consumers,
 *   not a binding in the file. Its `NamespaceExportDeclaration` is a child of
 *   the source file and so passes the walk, and it too sits happily beside an
 *   export of the same name.
 *
 * Everything else that reaches here does bind at the top level: a script
 * file's own `declare const` (appending the export makes the file a module and
 * puts both in the same scope), and a module's unexported `import name = …`.
 */
function declaresInFileScope(
  typeScript: TypeScriptModule,
  declaration: Declaration,
  sourceFile: SourceFile,
): boolean {
  if (
    declaration.getSourceFile() !== sourceFile ||
    typeScript.isNamespaceExportDeclaration(declaration)
  ) {
    return false
  }
  for (
    let node: Node | undefined = declaration.parent;
    node !== undefined && !typeScript.isSourceFile(node);
    node = node.parent
  ) {
    if (typeScript.isModuleDeclaration(node)) {
      return false
    }
  }
  return true
}

/**
 * Where a statement's block starts for replacement purposes: the doc comment
 * directly above it when one is there, otherwise the statement itself. Only a
 * `/** … *\/` comment separated from the statement by nothing but whitespace
 * counts, so a license banner further up is never swallowed.
 */
function declarationBlockStart(
  source: string,
  sourceFile: SourceFile,
  statement: Statement,
): number {
  const typeScript = loadTypeScript()
  const start = statement.getStart(sourceFile)
  const comments =
    typeScript.getLeadingCommentRanges(source, statement.getFullStart()) ?? []
  for (const comment of comments) {
    if (
      source.startsWith('/**', comment.pos) &&
      source.slice(comment.end, start).trim() === ''
    ) {
      return comment.pos
    }
  }
  return start
}

function parseDeclarationSource(source: string) {
  const typeScript = loadTypeScript()
  const parsed = typeScript.createSourceFile(
    'index.d.ts',
    source,
    typeScript.ScriptTarget.Latest,
    true,
    typeScript.ScriptKind.TS,
  )
  const diagnostics = (
    parsed as typeof parsed & {
      parseDiagnostics: readonly Diagnostic[]
    }
  ).parseDiagnostics
  if (diagnostics.length > 0) {
    throw new Error(
      `Failed to parse declaration source:\n${diagnostics
        .slice(0, 3)
        .map((diagnostic) =>
          typeScript.flattenDiagnosticMessageText(diagnostic.messageText, '\n'),
        )
        .join('\n')}`,
    )
  }
  return parsed
}

function hasNamedImport(
  statements: NodeArray<Statement>,
  typeImport: TypeImport,
): boolean {
  const typeScript = loadTypeScript()
  return statements.some(
    (statement) =>
      typeScript.isImportDeclaration(statement) &&
      typeScript.isStringLiteral(statement.moduleSpecifier) &&
      statement.moduleSpecifier.text === typeImport.module &&
      statement.importClause?.namedBindings !== undefined &&
      typeScript.isNamedImports(statement.importClause.namedBindings) &&
      statement.importClause.namedBindings.elements.some(
        (specifier) => specifier.name.text === typeImport.name,
      ),
  )
}

function leadingDeclarationPreambleEnd(
  source: string,
  parsed: ReturnType<typeof parseDeclarationSource>,
): number {
  const typeScript = loadTypeScript()
  const firstStatementStart =
    parsed.statements[0]?.getStart(parsed) ?? source.length
  const leadingComments =
    typeScript.getLeadingCommentRanges(
      source,
      parsed.statements[0]?.pos ?? 0,
    ) ?? []
  let offset = 0

  for (const comment of leadingComments) {
    if (
      comment.end > firstStatementStart ||
      source.slice(offset, comment.pos).trim()
    ) {
      break
    }
    if (source.startsWith('/**', comment.pos)) {
      break
    }
    offset = endOfLine(source, comment.end)
  }

  return offset
}

let loadedTypeScript: TypeScriptModule | undefined

function loadTypeScript(): TypeScriptModule {
  loadedTypeScript ??= require('typescript') as TypeScriptModule
  return loadedTypeScript
}

function endOfLine(source: string, offset: number): number {
  const newline = source.indexOf('\n', offset)
  return newline === -1 ? source.length : newline + 1
}

function insertDeclarationSource(
  source: string,
  offset: number,
  inserted: string,
  newline: string,
): string {
  const before = source.slice(0, offset)
  const after = source.slice(offset)
  const beforeSeparator =
    before.length > 0 && !before.endsWith('\n') ? newline : ''
  const afterSeparator =
    after.length > 0 && !after.startsWith('\n') ? newline : ''
  const finalNewline = after.length === 0 ? newline : ''
  return `${before}${beforeSeparator}${inserted}${afterSeparator}${after}${finalNewline}`
}

function expandToDeclarationLine(
  source: string,
  start: number,
  end: number,
): { start: number; end: number } {
  const lineStart = source.lastIndexOf('\n', start - 1) + 1
  const newline = source.indexOf('\n', end)
  const lineEnd = newline === -1 ? source.length : newline + 1
  const prefix = source.slice(lineStart, start)
  const suffix = source.slice(end, newline === -1 ? source.length : newline)
  return prefix.trim() || suffix.trim()
    ? { start, end }
    : { start: lineStart, end: lineEnd }
}

async function readIntermediateTypeFile(file: string) {
  const content = await readFileAsync(file, 'utf8')

  const defs = content
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      line = line.trim()
      const parsed = JSON.parse(line) as TypeDefLine
      if (parsed.js_doc) {
        parsed.js_doc = parsed.js_doc.replace(/\\n/g, '\n')
      }
      if (parsed.def) {
        parsed.def = decodeStructuralNewlines(parsed.def)
      }
      if (parsed.def_with_type_import_markers) {
        parsed.def_with_type_import_markers = decodeStructuralNewlines(
          parsed.def_with_type_import_markers,
        )
      }
      return parsed
    })

  // move all `struct` def to the very top
  // and order the rest alphabetically.
  return defs.sort((a, b) => {
    if (a.kind === TypeDefKind.Struct) {
      if (b.kind === TypeDefKind.Struct) {
        return a.name.localeCompare(b.name)
      }
      return -1
    } else if (b.kind === TypeDefKind.Struct) {
      return 1
    } else {
      return a.name.localeCompare(b.name)
    }
  })
}

function preprocessTypeDef(defs: TypeDefLine[]): Map<string, TypeDefLine[]> {
  const namespaceGrouped = new Map<string, TypeDefLine[]>()
  const classDefs = new Map<string, TypeDefLine>()

  for (const def of defs) {
    const namespace = def.js_mod ?? TOP_LEVEL_NAMESPACE
    if (!namespaceGrouped.has(namespace)) {
      namespaceGrouped.set(namespace, [])
    }

    const group = namespaceGrouped.get(namespace)!
    const classKey = `${namespace}\0${def.name}`

    if (def.kind === TypeDefKind.Struct) {
      group.push(def)
      classDefs.set(classKey, def)
    } else if (def.kind === TypeDefKind.Extends) {
      const classDef = classDefs.get(classKey)
      if (classDef) {
        classDef.extends = def.def
      }
    } else if (def.kind === TypeDefKind.Impl) {
      // merge `impl` into class definition
      const classDef = classDefs.get(classKey)
      if (classDef) {
        const asyncIterator = parseAsyncGeneratorImpl(def.def)
        if (asyncIterator) {
          classDef.asyncIterator = asyncIterator
        } else {
          if (classDef.def) {
            classDef.def += '\n'
          }

          classDef.def += def.def
          // Convert any remaining \n sequences in the merged def to actual newlines
          if (classDef.def) {
            classDef.def = classDef.def.replace(/\\n/g, '\n')
          }
        }
      }
    } else {
      group.push(def)
    }
  }

  return namespaceGrouped
}

export function correctStringIdent(src: string, ident: number): string {
  let bracketDepth = 0
  const result = src
    .split('\n')
    .map((rawLine) => {
      const line = rawLine.trim()
      if (line === '') {
        return ''
      }

      const isInMultilineComment = line.startsWith('*')
      const isTypeDeclaration = line.endsWith('=')
      const netBraces = isInMultilineComment ? 0 : netUnquotedBraces(line)

      if (netBraces < 0 && !line.startsWith('|')) {
        bracketDepth = Math.max(0, bracketDepth + netBraces)
      }

      let rightIndent = ident + bracketDepth * 2
      if (isInMultilineComment) {
        rightIndent += 1
      }

      if (netBraces > 0) {
        bracketDepth += netBraces
      } else if (
        isTypeDeclaration &&
        !isInMultilineComment &&
        netBraces === 0
      ) {
        bracketDepth += 1
      }

      return `${' '.repeat(rightIndent)}${line}`
    })
    .join('\n')

  return result
}

function netUnquotedBraces(line: string): number {
  let net = 0
  let quote: "'" | '"' | '`' | undefined
  let escaped = false
  for (const character of line) {
    if (quote) {
      if (escaped) {
        escaped = false
      } else if (character === '\\') {
        escaped = true
      } else if (character === quote) {
        quote = undefined
      }
      continue
    }
    if (character === "'" || character === '"' || character === '`') {
      quote = character
      continue
    }
    if (character === '{') {
      net += 1
    } else if (character === '}') {
      net -= 1
    }
  }
  return net
}
