import test from 'ava'

// Ensures index.cjs loaded the addon, so `loadedAddon()` can find it.
import '../index.cjs'
import { LOAD_IN_WORKER, runInWorker } from './multi-env-helpers.js'

// One addon image loaded twice on one thread gets two envs that share the
// image's statics. Each load must keep its own per-env state. These run in a
// worker so the extra load does not touch the env this process tests with.

test('a second load does not take the first load’s Reflect cache', async (t) => {
  if (process.env.WASI_TEST) {
    // A WASI instance has its own linear memory per load, so nothing is shared.
    t.pass()
    return
  }
  const result = await runInWorker(`
    ${LOAD_IN_WORKER}
    const make = () => new Error('boom', { cause: new Error('inner') })
    const first = load()
    const firstBefore = first.describeCapturedValue(make())
    const second = load()
    ;(async () => {
      parentPort.postMessage({
        firstBefore,
        first: first.describeCapturedValue(make()),
        second: second.describeCapturedValue(make()),
        firstRejection: await first.describePromiseRejection(
          Promise.reject(make()),
        ),
        secondRejection: await second.describePromiseRejection(
          Promise.reject(make()),
        ),
      })
    })()
  `)
  // Without a per-env cache the first load reads "JavaScript Error" and loses
  // the cause once the second load registers.
  const expected = 'GenericFailure|boom|inner'
  t.deepEqual(result, {
    firstBefore: expected,
    first: expected,
    second: expected,
    firstRejection: expected,
    secondRejection: expected,
  })
})

test('a second load does not cut the first load off from its references', async (t) => {
  if (process.env.WASI_TEST) {
    t.pass()
    return
  }
  const result = await runInWorker(`
    ${LOAD_IN_WORKER}
    const first = load()
    const value = { id: 'retained' }
    // The rejection reason is held as a reference in the first load's env and
    // read back on its JS thread once the task completes, after the second load.
    const pending = first.asyncTaskRejectWithCapturedValue(value)
    load()
    pending.then(
      () => parentPort.postMessage('resolved'),
      (reason) => parentPort.postMessage(reason === value ? 'same' : String(reason)),
    )
  `)
  // Without per-env custom-GC handles the second load takes over the thread's
  // handle, and the first load's references read as foreign.
  t.is(result, 'same')
})

// Each load defines its own classes, so a load must build, accept and check its
// own instances, not those of the newest load on the thread.
test('each load builds and checks its own classes', async (t) => {
  if (process.env.WASI_TEST) {
    t.pass()
    return
  }
  const result = await runInWorker(`
    ${LOAD_IN_WORKER}
    const checks = (binding) => {
      const run = (check) => {
        try {
          return check()
        } catch (error) {
          return error.message
        }
      }
      return {
        instanceOf: run(() =>
          binding.NinjaTurtle.isInstanceOf(binding.NinjaTurtle.newRaph()),
        ),
        classReturningExport: run(
          () => binding.returnEitherClass(-1) instanceof binding.JsClassForEither,
        ),
        classField: run(
          () => binding.createObjectWithClassField().bird instanceof binding.Bird,
        ),
        strictArgument: run(() =>
          binding.issue3427Strict(new binding.RenamedForIssue3427(7)),
        ),
        eitherArgument: run(() =>
          binding.issue3427Either(new binding.RenamedForIssue3427(8)),
        ),
        eitherOfClasses: run(() =>
          binding.receiveDifferentClass(new binding.AnotherClassForEither()),
        ),
      }
    }
    const first = load()
    const second = load()
    let crossLoad
    try {
      crossLoad = first.issue3427Strict(new second.RenamedForIssue3427(7))
    } catch (error) {
      crossLoad = 'rejected'
    }
    parentPort.postMessage({
      first: checks(first),
      second: checks(second),
      distinctClasses: first.NinjaTurtle !== second.NinjaTurtle,
      crossLoad,
    })
  `)
  const expected = {
    instanceOf: true,
    classReturningExport: true,
    classField: true,
    strictArgument: 7,
    eitherArgument: 8,
    eitherOfClasses: 100,
  }
  // Without per-env class lookups the first load builds and accepts the second
  // load's classes, and rejects its own instances.
  t.deepEqual(result, {
    first: expected,
    second: expected,
    distinctClasses: true,
    // Two loads are two sets of classes, like two realms.
    crossLoad: 'rejected',
  })
})

// Code generated by an older napi-derive looks classes up without an env. That
// lookup must still answer with a live load's class, skipping a load that
// failed to register its classes.
test('the env-less class lookup answers with the newest live load', async (t) => {
  if (process.env.WASI_TEST) {
    t.pass()
    return
  }
  const result = await runInWorker(`
    ${LOAD_IN_WORKER}
    const first = load()
    const second = load()
    const RealSymbol = Symbol
    globalThis.Symbol = null
    let failed
    try {
      load()
      failed = 'loaded'
    } catch (error) {
      failed = 'failed'
    }
    globalThis.Symbol = RealSymbol
    parentPort.postMessage({
      failed,
      fromFirst: first.legacyNinjaTurtleConstructor() === second.NinjaTurtle,
      fromSecond: second.legacyNinjaTurtleConstructor() === second.NinjaTurtle,
    })
  `)
  t.deepEqual(result, { failed: 'failed', fromFirst: true, fromSecond: true })
})
